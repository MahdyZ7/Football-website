// Generates .design-sync/shims/*-img.ts: downscaled webp data-URL copies of the
// large app images (roster player kits, tournament team logos) so the design
// bundle stays small. Uses the app's own `sharp` (a Next.js dependency).
// Re-run when those images change: node .design-sync/build-assets.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../package.json', import.meta.url));
const sharp = require('sharp');

const jobs = [
  ['assets/soccer_player_in_red_kit.png', 'kit-red-img.ts', 480],
  ['assets/soccer_player_in_blue_kit.png', 'kit-blue-img.ts', 480],
  ['assets/soccer_player_in_white_kit.png', 'kit-white-img.ts', 480],
];
for (const [src, out, size] of jobs) {
  const buf = await sharp(src).resize({ width: size, height: size, fit: 'inside' }).webp({ quality: 80 }).toBuffer();
  const meta = await sharp(buf).metadata();
  writeFileSync(new URL(`./shims/${out}`, import.meta.url),
    `// Generated by build-assets.mjs from ${src} - do not edit.\n` +
    `const img = { src: 'data:image/webp;base64,${buf.toString('base64')}', width: ${meta.width}, height: ${meta.height} };\nexport default img;\n`);
  console.log(out, (buf.length / 1024).toFixed(0), 'KB');
}
const logos = {};
for (const n of ['falcon', 'leopard', 'oryx', 'wolves']) {
  const buf = await sharp(`public/teams/${n}.webp`).resize({ width: 256, height: 256, fit: 'inside' }).webp({ quality: 85 }).toBuffer();
  logos[n] = buf;
  console.log(n, (buf.length / 1024).toFixed(0), 'KB');
}
writeFileSync(new URL('./shims/team-logos.ts', import.meta.url),
  '// Generated by build-assets.mjs from public/teams/*.webp (256px) - do not edit.\n' +
  Object.entries(logos).map(([n, b]) => `export const ${n} = 'data:image/webp;base64,${b.toString('base64')}';`).join('\n') + '\n');
